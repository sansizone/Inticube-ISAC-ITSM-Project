-- 워크스페이스 즐겨찾기 (사용자별)
CREATE TABLE IF NOT EXISTS tb_board_favorite (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id   bigint NOT NULL REFERENCES tb_board(id),
    user_id    bigint NOT NULL REFERENCES tb_app_user(id),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_board_favorite UNIQUE (board_id, user_id)
);
CREATE INDEX IF NOT EXISTS ix_board_favorite_user ON tb_board_favorite (user_id);

-- 사이드바 워크스페이스 정렬 순서 (사용자별 위로/아래로 이동)
CREATE TABLE IF NOT EXISTS tb_board_order (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint NOT NULL REFERENCES tb_app_user(id),
    board_id   bigint NOT NULL REFERENCES tb_board(id),
    sort_order int    NOT NULL DEFAULT 0,
    CONSTRAINT uk_board_order UNIQUE (user_id, board_id)
);
CREATE INDEX IF NOT EXISTS ix_board_order_user ON tb_board_order (user_id);
