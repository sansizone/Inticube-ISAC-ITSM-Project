CREATE TABLE IF NOT EXISTS tb_ws_group (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_name  varchar(100) NOT NULL,
    description varchar(500),
    sort_order  integer      NOT NULL DEFAULT 0,
    created_by  bigint       REFERENCES tb_app_user(id),
    created_at  timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tb_ws_group_member (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id    bigint      NOT NULL REFERENCES tb_ws_group(id),
    user_id     bigint      NOT NULL REFERENCES tb_app_user(id),
    member_role varchar(10) NOT NULL,          -- ADMIN: 그룹 관리자, MEMBER: 멤버
    CONSTRAINT uk_ws_group_member UNIQUE (group_id, user_id)
);
CREATE INDEX IF NOT EXISTS ix_ws_group_member_user ON tb_ws_group_member (user_id);

ALTER TABLE tb_board ADD COLUMN IF NOT EXISTS ws_group_id bigint;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_board_ws_group') THEN
    ALTER TABLE tb_board ADD CONSTRAINT fk_board_ws_group FOREIGN KEY (ws_group_id) REFERENCES tb_ws_group(id);
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS ix_board_ws_group ON tb_board (ws_group_id);
