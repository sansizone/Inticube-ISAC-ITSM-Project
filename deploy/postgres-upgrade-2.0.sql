--  · '워크스페이스 묶음' 제거 → 프로젝트(보드)가 곧 워크스페이스. 멤버·공개 여부를 보드마다 가짐
--  · 보기 탭(TB_BOARD_VIEW), 기본 컬럼 설정(TB_BOARD.COLUMN_CONFIG), 연결 컬럼(REF_BOARD_ID/REF_COLUMN_ID)
-- 앱을 ddl-auto=update(기본)로 기동하면 아래 테이블·컬럼이 자동 추가되고, 기동 시
--   v1.9 기본 워크스페이스(또는 그 이전) 보드 → '모든 사용자 공개'
--   그 밖의 v1.9 워크스페이스 보드   → '멤버 전용' + 그 워크스페이스 멤버를 보드 멤버로 복사
--   만든 사람은 보드 관리자(OWNER), 보드마다 기본 보기 탭 6개 생성
-- 까지 자동으로 합니다. DB 계정에 DDL 권한이 없을 때만 DBA 가 먼저 실행하세요. 여러 번 실행해도 안전합니다.
-- 구 테이블(tb_workspace, tb_workspace_member)과 tb_board.workspace_id 는 이관에 쓰이므로 남겨 둡니다.
-- =====================================================================
SET search_path TO teamboard;

ALTER TABLE tb_board ADD COLUMN IF NOT EXISTS is_public boolean;
ALTER TABLE tb_board ADD COLUMN IF NOT EXISTS column_config text;

ALTER TABLE tb_board_column ADD COLUMN IF NOT EXISTS ref_board_id bigint;
ALTER TABLE tb_board_column ADD COLUMN IF NOT EXISTS ref_column_id bigint;

CREATE TABLE IF NOT EXISTS tb_board_member (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id bigint NOT NULL,
    user_id bigint NOT NULL REFERENCES tb_app_user(id),
    member_role varchar(10) NOT NULL,
    CONSTRAINT uk_board_member UNIQUE (board_id, user_id)
);
CREATE INDEX IF NOT EXISTS ix_board_member_user ON tb_board_member (user_id);

CREATE TABLE IF NOT EXISTS tb_board_view (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id bigint NOT NULL,
    view_name varchar(50) NOT NULL,
    view_type varchar(20) NOT NULL,
    view_config text,
    sort_order integer NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_view_board ON tb_board_view (board_id);
