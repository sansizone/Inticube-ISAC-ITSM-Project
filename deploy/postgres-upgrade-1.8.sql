SET search_path TO teamboard;

-- 하위 업무 / 외부 원본 ID
ALTER TABLE tb_item ADD COLUMN IF NOT EXISTS parent_id bigint;
ALTER TABLE tb_item ADD COLUMN IF NOT EXISTS external_id varchar(50);
CREATE INDEX IF NOT EXISTS ix_item_parent ON tb_item (parent_id);
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_item_parent') THEN
    ALTER TABLE tb_item ADD CONSTRAINT fk_item_parent FOREIGN KEY (parent_id) REFERENCES tb_item(id);
  END IF;
END $$;

-- 댓글 답글 / 원래 작성자 이름 / 외부 원본 ID
ALTER TABLE tb_item_update ADD COLUMN IF NOT EXISTS parent_id bigint;
ALTER TABLE tb_item_update ADD COLUMN IF NOT EXISTS author_name varchar(100);
ALTER TABLE tb_item_update ADD COLUMN IF NOT EXISTS external_id varchar(50);

-- 프로젝트별 사용자 정의 컬럼
CREATE TABLE IF NOT EXISTS tb_board_column (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id bigint NOT NULL REFERENCES tb_board(id),
    column_name varchar(100) NOT NULL,
    column_type varchar(20) NOT NULL,
    column_scope varchar(10) NOT NULL,
    sort_order integer NOT NULL,
    is_visible boolean NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_column_board ON tb_board_column (board_id);

-- 컬럼 값 (원본 문자열)
CREATE TABLE IF NOT EXISTS tb_item_value (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id bigint NOT NULL,
    column_id bigint NOT NULL,
    val_text text NOT NULL,
    CONSTRAINT uk_item_value UNIQUE (item_id, column_id)
);
CREATE INDEX IF NOT EXISTS ix_value_column ON tb_item_value (column_id);
