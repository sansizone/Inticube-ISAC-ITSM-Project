SET search_path TO teamboard;

CREATE TABLE IF NOT EXISTS tb_workspace (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_name varchar(100) NOT NULL,
    description varchar(500),
    color varchar(20),
    sort_order integer NOT NULL,
    is_default boolean NOT NULL,
    created_by bigint REFERENCES tb_app_user(id),
    created_at timestamp(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS tb_workspace_member (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id bigint NOT NULL,
    user_id bigint NOT NULL REFERENCES tb_app_user(id),
    member_role varchar(10) NOT NULL,
    CONSTRAINT uk_ws_member UNIQUE (workspace_id, user_id)
);
CREATE INDEX IF NOT EXISTS ix_ws_member_user ON tb_workspace_member (user_id);

ALTER TABLE tb_board ADD COLUMN IF NOT EXISTS workspace_id bigint;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_board_workspace') THEN
    ALTER TABLE tb_board ADD CONSTRAINT fk_board_workspace FOREIGN KEY (workspace_id) REFERENCES tb_workspace(id);
  END IF;
END $$;
